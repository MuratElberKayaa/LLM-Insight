"""Create frontend/.env.local (git-ignored) for the Next.js server from the root .env.

Standard library only. Never prints secret values:

    python -I scripts/dev/init_frontend_env.py --project-id 1 [--force]

Writes only what the dashboard server needs (SECURITY.md §2, CR-06):
- LLMI_API_BASE_URL         http://<LLMI_BIND_HOST>:<LLMI_PORT> (loopback only)
- LLMI_API_TOKEN            the backend's LLMI_ADMIN_TOKEN (server-side only, no NEXT_PUBLIC_)
- LLMI_DASHBOARD_PROJECT_ID the project the overview shows

The backend pepper, database URL and other secrets are deliberately not copied, so the
Next.js process never holds them. An existing file is left unchanged unless --force.
"""

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, ".env")
TARGET = os.path.join(ROOT, "frontend", ".env.local")
LOOPBACK = {"127.0.0.1", "localhost", "::1"}


def read_env(path: str) -> dict[str, str]:
    values: dict[str, str] = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            key, sep, value = line.rstrip("\n").partition("=")
            if sep and not line.lstrip().startswith("#"):
                values[key.strip()] = value.strip()
    return values


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--project-id", required=True, type=int, help="project id shown by the dashboard")
    parser.add_argument("--force", action="store_true", help="replace an existing frontend/.env.local")
    args = parser.parse_args()
    if args.project_id < 1:
        sys.exit("--project-id must be a positive integer")
    if not os.path.exists(SOURCE):
        sys.exit(".env not found; run python -I scripts/dev/init_env.py first")
    if os.path.exists(TARGET) and not args.force:
        print("frontend/.env.local already exists; left unchanged (use --force to replace).")
        return 0

    env = read_env(SOURCE)
    token = env.get("LLMI_ADMIN_TOKEN", "")
    if not re.fullmatch(r"[\x21-\x7e]{32,512}", token) or token == "CHANGE_ME":
        sys.exit("LLMI_ADMIN_TOKEN in .env is missing or a placeholder (value not shown)")
    host = env.get("LLMI_BIND_HOST", "127.0.0.1")
    port = env.get("LLMI_PORT", "8000")
    if host not in LOOPBACK or not port.isdigit():
        sys.exit("LLMI_BIND_HOST must be a loopback address and LLMI_PORT a number")
    url_host = f"[{host}]" if host == "::1" else host

    content = (
        "# Generated by scripts/dev/init_frontend_env.py. Git-ignored. Server-side only:\n"
        "# never rename these to NEXT_PUBLIC_* (that would ship them to the browser).\n"
        f"LLMI_API_BASE_URL=http://{url_host}:{port}\n"
        f"LLMI_API_TOKEN={token}\n"
        f"LLMI_DASHBOARD_PROJECT_ID={args.project_id}\n"
    )
    tmp = TARGET + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    os.replace(tmp, TARGET)
    print(
        "Wrote frontend/.env.local: LLMI_API_BASE_URL, LLMI_API_TOKEN (value not shown), "
        f"LLMI_DASHBOARD_PROJECT_ID={args.project_id}."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
